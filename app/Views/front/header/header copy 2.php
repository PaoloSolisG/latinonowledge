<script>
// Enhanced Header JavaScript
document.addEventListener('DOMContentLoaded', function() {
    // Sticky Navigation
    const mainNav = document.getElementById('mainNav');
    const headerTopBar = document.querySelector('.header-top-bar');
    
    function handleScroll() {
        const scrollY = window.scrollY;
        const topBarHeight = headerTopBar ? headerTopBar.offsetHeight : 0;
        
        if (scrollY > topBarHeight + 50) {
            mainNav.classList.add('sticky');
            document.body.style.paddingTop = mainNav.offsetHeight + 'px';
        } else {
            mainNav.classList.remove('sticky');
            document.body.style.paddingTop = '0';
        }
    }
    
    window.addEventListener('scroll', handleScroll);
    
    // Mobile Menu Toggle
    const mobileMenuBtn = document.getElementById('mobileMenuBtn');
    const mobileCloseBtn = document.getElementById('mobileCloseBtn');
    const mobileMenuOverlay = document.getElementById('mobileMenuOverlay');
    const hamburger = document.querySelector('.hamburger');
    
    function toggleMobileMenu() {
        mobileMenuOverlay.classList.toggle('active');
        hamburger.classList.toggle('active');
        document.body.style.overflow = mobileMenuOverlay.classList.contains('active') ? 'hidden' : 'auto';
    }
    
    mobileMenuBtn.addEventListener('click', toggleMobileMenu);
    mobileCloseBtn.addEventListener('click', toggleMobileMenu);
    
    // Close mobile menu when clicking overlay
    mobileMenuOverlay.addEventListener('click', function(e) {
        if (e.target === mobileMenuOverlay) {
            toggleMobileMenu();
        }
    });
    
    // Mobile Dropdown Toggle
    document.querySelectorAll('.mobile-nav-dropdown .dropdown-toggle').forEach(toggle => {
        toggle.addEventListener('click', function(e) {
            e.preventDefault();
            const dropdownContent = this.nextElementSibling;
            const chevron = this.querySelector('.fa-chevron-down');
            
            dropdownContent.classList.toggle('active');
            chevron.style.transform = dropdownContent.classList.contains('active') 
                ? 'rotate(180deg)' : 'rotate(0)';
        });
    });
    
    // Smooth Scrolling for Navigation Links
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            e.preventDefault();
            const targetId = this.getAttribute('href').substring(1);
            const targetElement = document.getElementById(targetId) || 
                                 document.querySelector(`[data-section="${targetId}"]`) ||
                                 document.querySelector(`.${targetId}-section`);
            
            if (targetElement) {
                const headerHeight = mainNav.offsetHeight + (headerTopBar ? headerTopBar.offsetHeight : 0);
                const targetPosition = targetElement.offsetTop - headerHeight - 20;
                
                window.scrollTo({
                    top: targetPosition,
                    behavior: 'smooth'
                });
                
                // Close mobile menu if open
                if (mobileMenuOverlay.classList.contains('active')) {
                    toggleMobileMenu();
                }
                
                // Update active nav link
                updateActiveNavLink(this);
            }
        });
    });
    
    // Update Active Navigation Link
    function updateActiveNavLink(clickedLink) {
        document.querySelectorAll('.nav-link').forEach(link => {
            link.classList.remove('active');
        });
        
        const href = clickedLink.getAttribute('href');
        document.querySelectorAll(`a[href="${href}"]`).forEach(link => {
            if (link.classList.contains('nav-link')) {
                link.classList.add('active');
            }
        });
    }
    
    // Intersection Observer for Active Navigation
    const sections = document.querySelectorAll('section[id], div[id]');
    const navLinks = document.querySelectorAll('.nav-link[href^="#"]');
    
    const observerOptions = {
        threshold: 0.3,
        rootMargin: '-80px 0px -80px 0px'
    };
    
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const id = entry.target.id;
                navLinks.forEach(link => {
                    link.classList.remove('active');
                    if (link.getAttribute('href') === `#${id}`) {
                        link.classList.add('active');
                    }
                });
            }
        });
    }, observerOptions);
    
    sections.forEach(section => {
        observer.observe(section);
    });
    
    // Service Item Click Handlers
    document.querySelectorAll('.service-item').forEach(item => {
        item.addEventListener('click', function() {
            const serviceName = this.querySelector('h5').textContent.toLowerCase();
            const serviceUrl = getServiceUrl(serviceName);
            if (serviceUrl) {
                window.open(serviceUrl, '_blank');
            }
        });
    });
    
    function getServiceUrl(serviceName) {
        const serviceUrls = {
            'tax preparation': 'https://latino-knowledge.ueniweb.com/services/financial-solutions/tax-preparation-150515038',
            'accounting & financial management': 'https://latino-knowledge.ueniweb.com/services/financial-solutions/accounting-and-financial-management-150515039',
            'business startup assistance': 'https://latino-knowledge.ueniweb.com/services/financial-solutions/business-startup-assistance-150515040',
            'itin application support': 'https://latino-knowledge.ueniweb.com/services/financial-solutions/itin-application-support-150515041'
        };
        
        return serviceUrls[serviceName] || null;
    }
    
    // Add loading animation to CTA buttons
    document.querySelectorAll('.cta-btn, .mobile-cta-btn').forEach(btn => {
        btn.addEventListener('click', function() {
            if (this.href.includes('calendly')) {
                const originalText = this.innerHTML;
                this.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Loading...';
                
                setTimeout(() => {
                    this.innerHTML = originalText;
                }, 2000);
            }
        });
    });
});

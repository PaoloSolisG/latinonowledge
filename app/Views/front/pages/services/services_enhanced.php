        if (!selectedDate) {
            alert('Please select a date for your appointment.');
            return;
        }
        
        if (!selectedTime) {
            alert('Please select a time for your appointment.');
            return;
        }
        
        // Update summary in step 2
        updateBookingSummary(selectedService, selectedDate, selectedTime);
        
        // Show step 2
        showStep(2);
    });

